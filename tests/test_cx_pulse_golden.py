"""Golden test: a HubSpot CX export must keep producing exactly the same results.

Guards the codebook refactor (IMPLEMENTATION_PLAN.md M2–M7): the coded variables,
every cell of the tables workbook, and the analyst-style data sheets are compared
against a stored snapshot. The input is synthetic (no client data), generated by
tests/fixtures/exports/make_hubspot_cx_sample.py.

After an *intended* output change, regenerate the snapshot and review its diff:

    UPDATE_GOLDEN=1 python -m pytest tests/test_cx_pulse_golden.py
"""

import hashlib
import io
import json
import os
from pathlib import Path

import pandas as pd
import pytest
from openpyxl import load_workbook

from routers.auto_analyze import _run_auto_analyze
from services.codebook.infer import infer_codebook
from services.data_loader import load_data, read_raw
from services.data_workbook import append_data_workbook
from services.setups import apply_setup, get_setup

FIXTURE = Path(__file__).parent / "fixtures" / "exports" / "hubspot_cx_sample.xlsx"
GOLDEN = Path(__file__).parent / "snapshots" / "hubspot_cx_sample_golden.json"
DATA_SHEETS = {"FULL DATA PULSE", "Detractors", "Promoters", "Single", "Dual", "Triple",
               "Exam officers", "Teachers", "Leaders"}


def _cell(value) -> str | None:
    if value is None:
        return None
    if isinstance(value, float):
        return repr(round(value, 6))
    return str(value)


def _codebook(file_bytes: bytes):
    """Inferred coding + the HubSpot CX Pulse setup (the client rules live there, not in code)."""
    raw = read_raw(file_bytes, FIXTURE.name)
    codebook, applied, skipped = apply_setup(infer_codebook(raw), get_setup("hubspot_cx_pulse"), raw.df)
    assert not skipped, skipped
    return codebook


def _variables(file_bytes: bytes) -> dict:
    """Coded variables: label, value labels and the distribution of codes."""
    data = load_data(file_bytes, FIXTURE.name, _codebook(file_bytes))
    labels = data.meta.column_names_to_labels
    value_labels = data.meta.variable_value_labels
    out = {}
    for col in data.df.columns:
        series = data.df[col]
        entry = {"label": labels.get(col), "dtype": str(series.dtype), "n": int(series.notna().sum())}
        if col in value_labels:
            entry["value_labels"] = {repr(float(k)): v for k, v in sorted(value_labels[col].items())}
            entry["counts"] = {repr(float(k)): int(v) for k, v in series.value_counts().sort_index().items()}
        out[col] = entry
    return out


def _workbook(file_bytes: bytes) -> dict:
    codebook = _codebook(file_bytes)
    result = _run_auto_analyze(file_bytes, FIXTURE.name, {"_codebook": codebook})
    excel = append_data_workbook(result["excel_bytes"], file_bytes, FIXTURE.name, codebook)
    wb = load_workbook(io.BytesIO(excel))

    tables, data_sheets = {}, {}
    for ws in wb.worksheets:
        rows = [[_cell(v) for v in row] for row in ws.iter_rows(values_only=True)]
        if ws.title not in DATA_SHEETS:
            tables[ws.title] = rows  # every cell
            continue
        # Data sheets are large: headers + totals formulas verbatim, columns as fingerprints
        columns = list(zip(*rows[3:])) if len(rows) > 3 else []
        data_sheets[ws.title] = {
            "headers": rows[0], "percent_row": rows[1], "count_row": rows[2],
            "respondents": len(rows) - 3,
            "column_fingerprints": [hashlib.sha1(json.dumps(c).encode()).hexdigest()[:12] for c in columns],
        }
    return {"sheet_order": wb.sheetnames, "tables": tables, "data_sheets": data_sheets,
            "banners": result["summary"]["banners"]}


@pytest.fixture(scope="module")
def actual() -> dict:
    file_bytes = FIXTURE.read_bytes()
    return {"variables": _variables(file_bytes), **_workbook(file_bytes)}


def test_golden_snapshot(actual):
    if os.environ.get("UPDATE_GOLDEN"):
        GOLDEN.parent.mkdir(exist_ok=True)
        GOLDEN.write_text(json.dumps(actual, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        pytest.skip(f"golden snapshot rewritten: {GOLDEN}")

    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert actual["sheet_order"] == expected["sheet_order"]
    assert actual["banners"] == expected["banners"]
    for name, var in expected["variables"].items():
        assert actual["variables"].get(name) == var, f"variable {name} changed"
    assert set(actual["variables"]) == set(expected["variables"]), "variables added/removed"
    for sheet, rows in expected["tables"].items():
        assert actual["tables"].get(sheet) == rows, f"table sheet '{sheet}' changed"
    for sheet, summary in expected["data_sheets"].items():
        assert actual["data_sheets"].get(sheet) == summary, f"data sheet '{sheet}' changed"


def test_fixture_is_reproducible():
    """The committed fixture is exactly what the generator produces (no hand edits)."""
    from tests.fixtures.exports.make_hubspot_cx_sample import build

    buf = io.BytesIO()
    build().to_excel(buf, index=False)  # same round trip as the committed file
    buf.seek(0)
    pd.testing.assert_frame_equal(pd.read_excel(FIXTURE), pd.read_excel(buf))
